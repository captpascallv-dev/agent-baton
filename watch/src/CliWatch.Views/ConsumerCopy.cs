    public static UiLang Parse(string? raw)
    {
        if (string.IsNullOrWhiteSpace(raw)) return UiLang.Zh;
        var t = raw.Trim();
        if (t.Equals("en", StringComparison.OrdinalIgnoreCase)
            || t.Equals("en-US", StringComparison.OrdinalIgnoreCase)
            || t.Equals("english", StringComparison.OrdinalIgnoreCase)
            || t.Equals("en_us", StringComparison.OrdinalIgnoreCase))
        {
            return UiLang.En;
        }

        if (t.Equals("zh", StringComparison.OrdinalIgnoreCase)
            || t.Equals("zh-CN", StringComparison.OrdinalIgnoreCase)
            || t.Equals("zh_cn", StringComparison.OrdinalIgnoreCase)
            || t.Equals("chinese", StringComparison.OrdinalIgnoreCase)
            || t.Equals("中文", StringComparison.Ordinal))
        {
            return UiLang.Zh;
        }

        return UiLang.Zh;
    }

    public static string Code(UiLang lang) => lang == UiLang.En ? "en" : "zh";

    public static string T(UiLang lang, string key) =>
        lang == UiLang.En
            ? (EnChrome.TryGetValue(key, out var en) ? en : key)
            : (ZhChrome.TryGetValue(key, out var zh) ? zh : key);

    public static string L(UiLang lang, string zh, string en) => lang == UiLang.En ? en : zh;

    public static string Localize(string text, UiLang lang)
    {
        if (lang != UiLang.En || string.IsNullOrEmpty(text)) return text;
        var s = text;
        foreach (var (zh, en) in Fragments)
        {
            if (s.Contains(zh, StringComparison.Ordinal))
                s = s.Replace(zh, en, StringComparison.Ordinal);
        }

        return s.Replace("。", ". ", StringComparison.Ordinal)
            .Replace("；", "; ", StringComparison.Ordinal)
            .Replace("：", ": ", StringComparison.Ordinal);
    }

